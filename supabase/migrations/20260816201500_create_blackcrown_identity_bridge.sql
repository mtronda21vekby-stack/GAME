create or replace function public.blackcrown_grant_entitlement(
  p_site_user_id text,
  p_entitlement_key text,
  p_source text default 'admin',
  p_expires_at timestamptz default null,
  p_metadata jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_account_id uuid;
begin
  if p_site_user_id is null
     or p_site_user_id !~ '^[A-Za-z0-9_.:@-]{1,160}$' then
    raise exception using errcode = 'P0001', message = 'invalid_site_user_id';
  end if;
  if p_entitlement_key is null
     or p_entitlement_key !~ '^[a-z0-9._-]{1,80}$' then
    raise exception using errcode = 'P0001', message = 'invalid_entitlement_key';
  end if;
  if p_source not in ('payment', 'admin', 'promo', 'migration', 'system') then
    raise exception using errcode = 'P0001', message = 'invalid_entitlement_source';
  end if;
  if p_expires_at is not null and p_expires_at <= now() then
    raise exception using errcode = 'P0001', message = 'invalid_entitlement_expiry';
  end if;
  if p_metadata is null or jsonb_typeof(p_metadata) <> 'object' then
    raise exception using errcode = 'P0001', message = 'invalid_entitlement_metadata';
  end if;

  insert into public.blackcrown_accounts(site_user_id)
  values (p_site_user_id)
  on conflict (site_user_id) do update set updated_at = now()
  returning id into v_account_id;

  insert into public.blackcrown_entitlements(
    account_id,
    entitlement_key,
    status,
    source,
    starts_at,
    expires_at,
    metadata
  ) values (
    v_account_id,
    p_entitlement_key,
    'active',
    p_source,
    now(),
    p_expires_at,
    p_metadata
  )
  on conflict (account_id, entitlement_key) do update set
    status = 'active',
    source = excluded.source,
    starts_at = now(),
    expires_at = excluded.expires_at,
    metadata = excluded.metadata,
    updated_at = now();

  insert into public.blackcrown_account_events(
    account_id,
    event_type,
    actor,
    metadata
  ) values (
    v_account_id,
    'entitlement.granted',
    p_source,
    jsonb_build_object(
      'entitlement_key', p_entitlement_key,
      'expires_at', p_expires_at
    )
  );
end;
$$;

create or replace function public.blackcrown_revoke_entitlement(
  p_site_user_id text,
  p_entitlement_key text,
  p_actor text default 'admin'
)
returns boolean
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_account_id uuid;
  v_updated integer;
begin
  select id into v_account_id
  from public.blackcrown_accounts
  where site_user_id = p_site_user_id;

  if not found then
    return false;
  end if;

  update public.blackcrown_entitlements
  set status = 'revoked', updated_at = now()
  where account_id = v_account_id
    and entitlement_key = p_entitlement_key
    and status <> 'revoked';
  get diagnostics v_updated = row_count;

  if v_updated > 0 then
    insert into public.blackcrown_account_events(
      account_id,
      event_type,
      actor,
      metadata
    ) values (
      v_account_id,
      'entitlement.revoked',
      left(regexp_replace(lower(coalesce(p_actor, 'admin')), '[^a-z0-9._-]', '', 'g'), 40),
      jsonb_build_object('entitlement_key', p_entitlement_key)
    );
  end if;

  return v_updated > 0;
end;
$$;

