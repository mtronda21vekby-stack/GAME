create or replace function public.blackcrown_issue_telegram_link_code(
  p_site_user_id text,
  p_code_hash text,
  p_expires_at timestamptz
)
returns table(expires_at timestamptz)
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_account_id uuid;
begin
  if p_site_user_id is null
     or p_site_user_id !~ '^[A-Za-z0-9_.:@-]{1,160}$' then
    raise exception using errcode = 'P0001', message = 'invalid_site_user_id';
  end if;
  if p_code_hash is null or p_code_hash !~ '^[0-9a-f]{64}$' then
    raise exception using errcode = 'P0001', message = 'invalid_link_code_hash';
  end if;
  if p_expires_at <= now()
     or p_expires_at > now() + interval '15 minutes' then
    raise exception using errcode = 'P0001', message = 'invalid_link_expiry';
  end if;

  insert into public.blackcrown_accounts(site_user_id)
  values (p_site_user_id)
  on conflict (site_user_id) do update set updated_at = now()
  returning id into v_account_id;

  if exists (
    select 1
    from public.blackcrown_telegram_link_codes
    where account_id = v_account_id
      and consumed_at is null
      and expires_at > now()
      and created_at > now() - interval '15 seconds'
  ) then
    raise exception using errcode = 'P0001', message = 'link_rate_limited';
  end if;

  update public.blackcrown_telegram_link_codes
  set consumed_at = coalesce(consumed_at, now())
  where account_id = v_account_id
    and consumed_at is null;

  delete from public.blackcrown_telegram_link_codes
  where expires_at < now() - interval '1 day';

  insert into public.blackcrown_telegram_link_codes(
    code_hash,
    account_id,
    expires_at
  ) values (
    p_code_hash,
    v_account_id,
    p_expires_at
  );

  insert into public.blackcrown_account_events(
    account_id,
    event_type,
    actor,
    metadata
  ) values (
    v_account_id,
    'telegram.link_code_issued',
    'site',
    jsonb_build_object('expires_at', p_expires_at)
  );

  return query select p_expires_at;
end;
$$;

create or replace function public.blackcrown_consume_telegram_link_code(
  p_code_hash text,
  p_telegram_user_id bigint,
  p_telegram_chat_id bigint,
  p_telegram_username text default null
)
returns table(
  linked boolean,
  premium_active boolean,
  entitlement_keys text[]
)
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_code public.blackcrown_telegram_link_codes%rowtype;
  v_conflicting_account uuid;
  v_conflicting_telegram bigint;
  v_username text;
begin
  if p_code_hash is null or p_code_hash !~ '^[0-9a-f]{64}$' then
    raise exception using errcode = 'P0001', message = 'invalid_or_expired_link_code';
  end if;
  if p_telegram_user_id is null
     or p_telegram_user_id <= 0
     or p_telegram_chat_id is null
     or p_telegram_chat_id <> p_telegram_user_id then
    raise exception using errcode = 'P0001', message = 'private_chat_required';
  end if;

  v_username := nullif(left(regexp_replace(
    coalesce(p_telegram_username, ''),
    '[^A-Za-z0-9_]',
    '',
    'g'
  ), 64), '');

  select * into v_code
  from public.blackcrown_telegram_link_codes
  where code_hash = p_code_hash
  for update;

  if not found
     or v_code.consumed_at is not null
     or v_code.expires_at <= now() then
    raise exception using errcode = 'P0001', message = 'invalid_or_expired_link_code';
  end if;

  select account_id into v_conflicting_account
  from public.blackcrown_telegram_links
  where telegram_user_id = p_telegram_user_id;

  if found and v_conflicting_account <> v_code.account_id then
    raise exception using errcode = 'P0001', message = 'telegram_already_linked';
  end if;

  select telegram_user_id into v_conflicting_telegram
  from public.blackcrown_telegram_links
  where account_id = v_code.account_id;

  if found and v_conflicting_telegram <> p_telegram_user_id then
    raise exception using errcode = 'P0001', message = 'account_already_linked';
  end if;

  insert into public.blackcrown_telegram_links(
    account_id,
    telegram_user_id,
    telegram_chat_id,
    telegram_username
  ) values (
    v_code.account_id,
    p_telegram_user_id,
    p_telegram_chat_id,
    v_username
  )
  on conflict (account_id) do update set
    telegram_user_id = excluded.telegram_user_id,
    telegram_chat_id = excluded.telegram_chat_id,
    telegram_username = excluded.telegram_username,
    updated_at = now();

  update public.blackcrown_telegram_link_codes
  set consumed_at = now()
  where code_hash = p_code_hash;

  insert into public.blackcrown_account_events(
    account_id,
    event_type,
    actor,
    metadata
  ) values (
    v_code.account_id,
    'telegram.linked',
    'telegram',
    jsonb_build_object(
      'telegram_user_id', p_telegram_user_id,
      'telegram_username', v_username
    )
  );

  return query
  select
    true,
    exists (
      select 1
      from public.blackcrown_entitlements e
      where e.account_id = v_code.account_id
        and e.entitlement_key = 'blackcrown.premium'
        and e.status = 'active'
        and e.starts_at <= now()
        and (e.expires_at is null or e.expires_at > now())
    ),
    coalesce((
      select array_agg(e.entitlement_key order by e.entitlement_key)
      from public.blackcrown_entitlements e
      where e.account_id = v_code.account_id
        and e.status = 'active'
        and e.starts_at <= now()
        and (e.expires_at is null or e.expires_at > now())
    ), array[]::text[]);
end;
$$;

create or replace function public.blackcrown_get_site_telegram_status(
  p_site_user_id text
)
returns table(
  linked boolean,
  telegram_username text,
  linked_at timestamptz,
  premium_active boolean,
  entitlement_keys text[]
)
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_account_id uuid;
begin
  select id into v_account_id
  from public.blackcrown_accounts
  where site_user_id = p_site_user_id;

  if not found then
    return query
    select false, null::text, null::timestamptz, false, array[]::text[];
    return;
  end if;

  return query
  select
    l.account_id is not null,
    l.telegram_username,
    l.linked_at,
    exists (
      select 1
      from public.blackcrown_entitlements e
      where e.account_id = v_account_id
        and e.entitlement_key = 'blackcrown.premium'
        and e.status = 'active'
        and e.starts_at <= now()
        and (e.expires_at is null or e.expires_at > now())
    ),
    coalesce((
      select array_agg(e.entitlement_key order by e.entitlement_key)
      from public.blackcrown_entitlements e
      where e.account_id = v_account_id
        and e.status = 'active'
        and e.starts_at <= now()
        and (e.expires_at is null or e.expires_at > now())
    ), array[]::text[])
  from (select v_account_id as account_id) a
  left join public.blackcrown_telegram_links l
    on l.account_id = a.account_id;
end;
$$;

create or replace function public.blackcrown_get_telegram_identity(
  p_telegram_user_id bigint
)
returns table(
  site_user_id text,
  premium_active boolean,
  entitlement_keys text[]
)
language sql
security definer
set search_path = public, extensions
stable
as $$
  select
    a.site_user_id,
    exists (
      select 1
      from public.blackcrown_entitlements e
      where e.account_id = a.id
        and e.entitlement_key = 'blackcrown.premium'
        and e.status = 'active'
        and e.starts_at <= now()
        and (e.expires_at is null or e.expires_at > now())
    ) as premium_active,
    coalesce((
      select array_agg(e.entitlement_key order by e.entitlement_key)
      from public.blackcrown_entitlements e
      where e.account_id = a.id
        and e.status = 'active'
        and e.starts_at <= now()
        and (e.expires_at is null or e.expires_at > now())
    ), array[]::text[]) as entitlement_keys
  from public.blackcrown_telegram_links l
  join public.blackcrown_accounts a on a.id = l.account_id
  where l.telegram_user_id = p_telegram_user_id;
$$;

create or replace function public.blackcrown_unlink_site_telegram(
  p_site_user_id text
)
returns boolean
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_account_id uuid;
  v_deleted integer;
begin
  select id into v_account_id
  from public.blackcrown_accounts
  where site_user_id = p_site_user_id;

  if not found then
    return false;
  end if;

  delete from public.blackcrown_telegram_links
  where account_id = v_account_id;
