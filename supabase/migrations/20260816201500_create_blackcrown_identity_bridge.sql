  if v_deleted > 0 then
    insert into public.blackcrown_account_events(
      account_id,
      event_type,
      actor
    ) values (
      v_account_id,
      'telegram.unlinked',
      'site'
    );
  end if;

  return v_deleted > 0;
end;
$$;

