create or replace function public.blackcrown_bridge_touch_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.blackcrown_accounts (
  id uuid primary key default gen_random_uuid(),
  site_user_id text not null unique
    check (site_user_id ~ '^[A-Za-z0-9_.:@-]{1,160}$'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.blackcrown_telegram_links (
  account_id uuid primary key
    references public.blackcrown_accounts(id) on delete cascade,
  telegram_user_id bigint not null unique check (telegram_user_id > 0),
  telegram_chat_id bigint not null check (telegram_chat_id > 0),
  telegram_username text
    check (telegram_username is null or telegram_username ~ '^[A-Za-z0-9_]{1,64}$'),
  linked_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (telegram_chat_id = telegram_user_id)
);

create table if not exists public.blackcrown_telegram_link_codes (
  code_hash text primary key check (code_hash ~ '^[0-9a-f]{64}$'),
  account_id uuid not null
    references public.blackcrown_accounts(id) on delete cascade,
  expires_at timestamptz not null,
  consumed_at timestamptz,
  created_at timestamptz not null default now(),
  check (expires_at > created_at),
  check (consumed_at is null or consumed_at >= created_at)
);

create index if not exists blackcrown_link_codes_account_idx
  on public.blackcrown_telegram_link_codes(account_id, created_at desc);
create index if not exists blackcrown_link_codes_expiry_idx
  on public.blackcrown_telegram_link_codes(expires_at)
  where consumed_at is null;

create table if not exists public.blackcrown_entitlements (
  account_id uuid not null
    references public.blackcrown_accounts(id) on delete cascade,
  entitlement_key text not null
    check (entitlement_key ~ '^[a-z0-9._-]{1,80}$'),
  status text not null default 'active'
    check (status in ('active', 'revoked')),
  source text not null default 'system'
    check (source in ('payment', 'admin', 'promo', 'migration', 'system')),
  starts_at timestamptz not null default now(),
  expires_at timestamptz,
  metadata jsonb not null default '{}'::jsonb
    check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (account_id, entitlement_key),
  check (expires_at is null or expires_at > starts_at)
);

create index if not exists blackcrown_entitlements_active_idx
  on public.blackcrown_entitlements(account_id, entitlement_key)
  where status = 'active';

create table if not exists public.blackcrown_account_events (
  id bigint generated by default as identity primary key,
  account_id uuid
    references public.blackcrown_accounts(id) on delete set null,
  event_type text not null
    check (event_type ~ '^[a-z0-9._-]{1,80}$'),
  actor text not null default 'system'
    check (actor ~ '^[a-z0-9._-]{1,40}$'),
  metadata jsonb not null default '{}'::jsonb
    check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now()
);

create index if not exists blackcrown_account_events_account_idx
  on public.blackcrown_account_events(account_id, id desc);

