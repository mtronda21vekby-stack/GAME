create or replace function public.blackcrown_unlink_telegram(
  p_telegram_user_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_link public.blackcrown_account_links%rowtype;
begin
  if p_telegram_user_id is null or p_telegram_user_id <= 0 then
    return jsonb_build_object('ok', false, 'reason', 'invalid_telegram_identity');
  end if;

  delete from public.blackcrown_account_links
   where telegram_user_id = p_telegram_user_id
   returning * into v_link;

  if not found then
    return jsonb_build_object('ok', true, 'unlinked', false);
  end if;

  insert into public.blackcrown_account_link_events (
    site_user_id,
    telegram_user_id,
    event_type
  ) values (
    v_link.site_user_id,
    v_link.telegram_user_id,
    'unlinked_by_telegram'
  );

  return jsonb_build_object('ok', true, 'unlinked', true);
end;
$$;

