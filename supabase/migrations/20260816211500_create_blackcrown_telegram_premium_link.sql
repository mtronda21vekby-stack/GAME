create extension if not exists pgcrypto with schema extensions;

create table if not exists public.blackcrown_telegram_link_challenges (
  id uuid primary key default extensions.gen_random_uuid(),
  code_hash text not null unique check (code_hash ~ '^[0-9a-f]{64}$'),
  telegram_user_id bigint not null check (telegram_user_id > 0),
  telegram_chat_id bigint not null,
  telegram_username text,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  consumed_at timestamptz,
  check (expires_at > created_at)
);

create index if not exists blackcrown_link_challenges_telegram_idx
  on public.blackcrown_telegram_link_challenges (telegram_user_id, created_at desc);

create index if not exists blackcrown_link_challenges_expiry_idx
  on public.blackcrown_telegram_link_challenges (expires_at)
  where consumed_at is null;

create table if not exists public.blackcrown_account_links (
  site_user_id text primary key
    check (length(site_user_id) between 1 and 160)
    check (site_user_id ~ '^[A-Za-z0-9_.:@-]+$'),
  telegram_user_id bigint not null unique check (telegram_user_id > 0),
  telegram_chat_id bigint not null,
  telegram_username text,
  status text not null default 'active' check (status in ('active', 'revoked')),
  linked_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.blackcrown_entitlements (
  id uuid primary key default extensions.gen_random_uuid(),
  site_user_id text not null
    check (length(site_user_id) between 1 and 160)
    check (site_user_id ~ '^[A-Za-z0-9_.:@-]+$'),
  entitlement_key text not null
    check (length(entitlement_key) between 1 and 80)
    check (entitlement_key ~ '^[a-z0-9_.:-]+$'),
  status text not null default 'active' check (status in ('active', 'revoked', 'expired')),
  source text not null default 'manual' check (length(source) between 1 and 64),
  valid_from timestamptz not null default now(),
  valid_until timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (valid_until is null or valid_until > valid_from),
  unique (site_user_id, entitlement_key, source)
);

create index if not exists blackcrown_entitlements_active_idx
  on public.blackcrown_entitlements (site_user_id, entitlement_key, valid_until)
  where status = 'active';

create table if not exists public.blackcrown_account_link_events (
  id bigint generated by default as identity primary key,
  site_user_id text,
  telegram_user_id bigint,
  event_type text not null check (event_type in ('linked', 'link_refreshed', 'unlinked_by_telegram')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists blackcrown_account_link_events_site_idx
  on public.blackcrown_account_link_events (site_user_id, id desc);

create index if not exists blackcrown_account_link_events_telegram_idx
  on public.blackcrown_account_link_events (telegram_user_id, id desc);

alter table public.blackcrown_telegram_link_challenges enable row level security;
