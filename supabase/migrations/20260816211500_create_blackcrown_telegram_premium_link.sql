create or replace function public.blackcrown_create_telegram_link_challenge(
  p_code_hash text,
  p_telegram_user_id bigint,
  p_telegram_chat_id bigint,
  p_telegram_username text default null,
  p_ttl_seconds integer default 600
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_ttl integer;
  v_expires_at timestamptz;
  v_username text;
begin
  if p_code_hash is null or p_code_hash !~ '^[0-9a-f]{64}$' then
    return jsonb_build_object('ok', false, 'reason', 'invalid_code_hash');
  end if;
  if p_telegram_user_id is null or p_telegram_user_id <= 0 or p_telegram_chat_id is null then
    return jsonb_build_object('ok', false, 'reason', 'invalid_telegram_identity');
  end if;

  v_ttl := greatest(60, least(coalesce(p_ttl_seconds, 600), 900));
  v_expires_at := now() + make_interval(secs => v_ttl);
  v_username := nullif(left(regexp_replace(coalesce(p_telegram_username, ''), '[^A-Za-z0-9_]', '', 'g'), 64), '');

  update public.blackcrown_telegram_link_challenges
     set consumed_at = now()
   where telegram_user_id = p_telegram_user_id
     and consumed_at is null;

  delete from public.blackcrown_telegram_link_challenges
   where expires_at < now() - interval '1 day';

  insert into public.blackcrown_telegram_link_challenges (
    code_hash,
    telegram_user_id,
    telegram_chat_id,
    telegram_username,
    expires_at
  ) values (
    p_code_hash,
    p_telegram_user_id,
    p_telegram_chat_id,
    v_username,
    v_expires_at
  );

  return jsonb_build_object(
    'ok', true,
    'expires_at', v_expires_at,
    'ttl_seconds', v_ttl
  );
end;
$$;

create or replace function public.blackcrown_complete_telegram_link(
  p_code text,
  p_site_user_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_hash text;
  v_challenge public.blackcrown_telegram_link_challenges%rowtype;
  v_existing_site public.blackcrown_account_links%rowtype;
  v_existing_telegram public.blackcrown_account_links%rowtype;
  v_entitlements text[] := array[]::text[];
  v_premium boolean := false;
  v_event text := 'linked';
begin
  if p_code is null or length(p_code) < 32 or length(p_code) > 128 or p_code !~ '^[A-Za-z0-9_-]+$' then
    return jsonb_build_object('ok', false, 'reason', 'invalid_or_expired_code');
  end if;
  if p_site_user_id is null
     or length(p_site_user_id) < 1
     or length(p_site_user_id) > 160
     or p_site_user_id !~ '^[A-Za-z0-9_.:@-]+$' then
    return jsonb_build_object('ok', false, 'reason', 'invalid_site_user');
  end if;

  v_hash := encode(extensions.digest(convert_to(p_code, 'UTF8'), 'sha256'), 'hex');

  select *
    into v_challenge
    from public.blackcrown_telegram_link_challenges
   where code_hash = v_hash
     and consumed_at is null
     and expires_at > now()
   for update;

  if not found then
    return jsonb_build_object('ok', false, 'reason', 'invalid_or_expired_code');
  end if;

  select * into v_existing_site
    from public.blackcrown_account_links
   where site_user_id = p_site_user_id
     and status = 'active';

  if found and v_existing_site.telegram_user_id <> v_challenge.telegram_user_id then
    return jsonb_build_object('ok', false, 'reason', 'site_already_linked');
  end if;

  select * into v_existing_telegram
    from public.blackcrown_account_links
   where telegram_user_id = v_challenge.telegram_user_id
     and status = 'active';

  if found and v_existing_telegram.site_user_id <> p_site_user_id then
    return jsonb_build_object('ok', false, 'reason', 'telegram_already_linked');
  end if;

  if v_existing_site.site_user_id is not null then
    v_event := 'link_refreshed';
    update public.blackcrown_account_links
       set telegram_chat_id = v_challenge.telegram_chat_id,
           telegram_username = v_challenge.telegram_username,
           updated_at = now()
     where site_user_id = p_site_user_id;
  else
    insert into public.blackcrown_account_links (
      site_user_id,
      telegram_user_id,
      telegram_chat_id,
      telegram_username,
      status
    ) values (
      p_site_user_id,
      v_challenge.telegram_user_id,
      v_challenge.telegram_chat_id,
      v_challenge.telegram_username,
      'active'
    );
  end if;

  update public.blackcrown_telegram_link_challenges
     set consumed_at = now()
   where id = v_challenge.id;

  insert into public.blackcrown_account_link_events (
    site_user_id,
    telegram_user_id,
    event_type,
    metadata
  ) values (
    p_site_user_id,
    v_challenge.telegram_user_id,
    v_event,
    jsonb_build_object('challenge_id', v_challenge.id)
  );

  select coalesce(array_agg(entitlement_key order by entitlement_key), array[]::text[])
    into v_entitlements
    from public.blackcrown_entitlements
   where site_user_id = p_site_user_id
     and status = 'active'
     and valid_from <= now()
     and (valid_until is null or valid_until > now());

  v_premium := 'bco_premium' = any(v_entitlements);

  return jsonb_build_object(
    'ok', true,
    'linked', true,
    'premium', v_premium,
    'entitlements', to_jsonb(v_entitlements),
    'linked_at', now()
  );
exception
  when unique_violation then
    return jsonb_build_object('ok', false, 'reason', 'link_conflict');
end;
$$;

